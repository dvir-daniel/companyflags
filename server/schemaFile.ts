// server/schema.sql: the schema as the migrations leave it, to read in one place (the migrations are the history of
// how it got there). Made by `pnpm schema` from a new embedded database with every migration applied; a test
// (test/schema-file.test.ts) fails when it is out of date, so a change to the schema shows in review.
// It is for reading only: the server never runs it.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Queryable } from './db.ts';

export const SCHEMA_FILE = fileURLToPath(new URL('./schema.sql', import.meta.url));

/** The public schema, in a stable order: the tables with their columns and constraints, the indexes, the functions
 *  and the triggers. */
export async function currentSchema(db: Queryable): Promise<string> {
  const q = async <T>(sql: string) => (await db.query<T>(sql)).rows;
  const out: string[] = [
    '-- The schema as the migrations in server/migrations leave it. Made by `pnpm schema`: never edit it by hand.',
    '-- A schema change is a new migration file; then run `pnpm schema` and commit both.',
    '',
  ];
  const ext = await q<{ name: string }>(`select extname as name from pg_extension where extname <> 'plpgsql' order by 1`);
  for (const e of ext) out.push(`create extension ${e.name};`);
  if (ext.length) out.push('');
  const types = await q<{ name: string; labels: string[] }>(`select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' group by t.typname order by 1`);
  for (const t of types) out.push(`create type ${t.name} as enum (${t.labels.map((l) => `'${l}'`).join(', ')});`, '');
  const tables = await q<{ name: string }>(`select c.relname as name from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' order by 1`);
  for (const t of tables) {
    const cols = await q<{ line: string }>(`select '  ' || a.attname || ' ' || format_type(a.atttypid, a.atttypmod)
        || case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end
        || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                when d.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end
        || case when a.attnotnull and a.attidentity = '' then ' not null' else '' end as line
      from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      where a.attrelid = 'public.${t.name}'::regclass and a.attnum > 0 and not a.attisdropped order by a.attnum`);
    const cons = await q<{ line: string }>(`select '  constraint ' || conname || ' ' || pg_get_constraintdef(oid) as line
      from pg_constraint where conrelid = 'public.${t.name}'::regclass and contype <> 'n' order by contype, conname`);
    out.push(`create table ${t.name} (`, [...cols, ...cons].map((r) => r.line).join(',\n'), ');', '');
  }
  const indexes = await q<{ def: string }>(`select indexdef as def from pg_indexes i where schemaname = 'public'
    and not exists (select 1 from pg_constraint c where c.conname = i.indexname) order by tablename, indexname`);
  for (const i of indexes) out.push(`${i.def};`);
  if (indexes.length) out.push('');
  const fns = await q<{ def: string }>(`select pg_get_functiondef(p.oid) as def from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e') order by p.proname, p.oid::regprocedure::text`);
  for (const f of fns) out.push(`${f.def.trim()};`, '');
  const triggers = await q<{ def: string }>(`select pg_get_triggerdef(t.oid) as def from pg_trigger t join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and not t.tgisinternal order by c.relname, t.tgname`);
  for (const t of triggers) out.push(`${t.def};`);
  return `${out.join('\n').replace(/\n+$/, '')}\n`;
}

// pnpm schema: write server/schema.sql from a new embedded database
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { openDb } = await import('./db.ts');
  const { db } = await openDb();
  try {
    writeFileSync(SCHEMA_FILE, await currentSchema(db));
    console.log(`wrote ${SCHEMA_FILE}`);
  } finally {
    await db.close();
  }
}
